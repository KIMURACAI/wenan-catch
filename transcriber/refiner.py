# ═══════════════════════════════════════════════════════════
# 置信标签（返回附加信息）
# ═══════════════════════════════════════════════════════════


class RefineResult:
    """精炼结果"""
    def __init__(self, text: str, is_watermark: bool = False, quality: str = "good"):
        self.text = text
        self.is_watermark = is_watermark
        self.quality = quality  # "good", "watermark", "low_quality"

    def __bool__(self):
        return bool(self.text) and not self.is_watermark


def _is_watermark(text: str) -> bool:
    """判断是否为水印/片头片尾噪音"""
    if not text or len(text) < 4:
        return False
    for pattern in _WATERMARK_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return True
    return False


def _apply_common_fixes(text: str) -> str:
    """应用常见 ASR 错误修正"""
    # 优先匹配长词
    sorted_fixes = sorted(_COMMON_FIXES.items(), key=lambda x: -len(x[0]))
    for wrong, correct in sorted_fixes:
        if correct == '':
            # 空字符串表示删除
            text = text.replace(wrong, '')
        else:
            text = text.replace(wrong, correct)
    return text


def _normalize_punctuation(text: str) -> str:
    """统一标点，适合口播"""
    if not text:
        return text

    # 英文标点转中文
    text = text.replace(',', '，')
    text = text.replace('!', '！')
    text = text.replace('?', '？')
    text = text.replace(':', '：')
    text = text.replace(';', '；')

    # 多个标点合并
    text = re.sub(r'[，，]+', '，', text)
    text = re.sub(r'[。。]+', '。', text)
    text = re.sub(r'[！!]+', '！', text)

    # 去除开头标点
    text = text.lstrip('，。！？：；、')

    # 句末加句号
    text = text.strip()
    if text and text[-1] not in '。！？，':
        text += '。'

    return text


def refine_transcription(text: str, confidence: Optional[float] = None) -> RefineResult:
    """
    精炼 Whisper 转写结果

    Args:
        text: 原始转写文本
        confidence: 置信度（可选，用于辅助判断）

    Returns:
        RefineResult: 精炼结果
    """
    if not text:
        return RefineResult("", quality="empty")

    # 1. 水印检测
    if _is_watermark(text):
        return RefineResult("", is_watermark=True, quality="watermark")

    # 2. 常见错误修正
    text = _apply_common_fixes(text)

    # 3. 统一标点
    text = _normalize_punctuation(text)

    # 4. 去除多余空格
    text = re.sub(r'\s+', '', text)

    return RefineResult(text, quality="good")
